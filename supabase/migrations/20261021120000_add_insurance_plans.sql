-- Insurance plans
--
-- Providers create their own insurance plans and attach them to their cars.
-- When booking a car, the client picks one of the plans attached to it and
-- pays pricePerDay x rental days.
--
--   insurance_plan        one row per plan, owned by a provider
--   car_insurance_plan    which plans a car offers (many-to-many)
--   booking.insurance*    snapshot of the chosen plan at booking time
--
-- The tiers mirror the usual Albanian rental offers:
--   third_party    Third Party Liability
--   mini_kasko_70  Mini Kasko 70%
--   kasko_80       Kasko 80%
--   full           Full insurance
--
-- Depends on the private.* helpers from 20261019083105_harden_rls_and_roles.sql.

-- ---------------------------------------------------------------------------
-- insurance_plan
-- ---------------------------------------------------------------------------

create table if not exists public.insurance_plan (
  id bigint generated by default as identity primary key,
  "providerId" uuid not null references public.users (id) on delete cascade,
  tier text not null,
  name text not null,
  "pricePerDay" numeric(10,2) not null default 0,
  "coveragePercent" integer,
  coverage text[] not null default '{}'::text[],
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  constraint insurance_plan_tier_check
    check (tier in ('third_party', 'mini_kasko_70', 'kasko_80', 'full')),
  constraint insurance_plan_name_check
    check (char_length(btrim(name)) between 1 and 80),
  constraint insurance_plan_price_check
    check ("pricePerDay" >= 0),
  constraint insurance_plan_coverage_percent_check
    check ("coveragePercent" is null or "coveragePercent" between 1 and 100),
  constraint insurance_plan_coverage_check
    check (coverage <@ array[
      'third_party', 'accidents', 'natural_disasters', 'fire_lightning',
      'parking', 'glass_mirrors', 'tyres', 'theft', 'under_car', 'abroad',
      'roadside_assistance'
    ]::text[])
);

create index if not exists insurance_plan_provider_idx
  on public.insurance_plan ("providerId");

create or replace function private.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new."updatedAt" := now();
  return new;
end;
$$;

drop trigger if exists insurance_plan_touch_updated_at on public.insurance_plan;
create trigger insurance_plan_touch_updated_at
  before update on public.insurance_plan
  for each row execute function private.touch_updated_at();

-- A plan always stays with the provider who created it
create or replace function private.guard_insurance_plan_owner()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new."providerId" is distinct from old."providerId" then
    raise exception 'The owner of an insurance plan cannot be changed';
  end if;
  return new;
end;
$$;

drop trigger if exists insurance_plan_guard_owner on public.insurance_plan;
create trigger insurance_plan_guard_owner
  before update on public.insurance_plan
  for each row execute function private.guard_insurance_plan_owner();

alter table public.insurance_plan enable row level security;

drop policy if exists insurance_plan_select_public on public.insurance_plan;
drop policy if exists insurance_plan_insert on public.insurance_plan;
drop policy if exists insurance_plan_update on public.insurance_plan;
drop policy if exists insurance_plan_delete on public.insurance_plan;

-- Plans are shown to clients on the car and booking pages
create policy insurance_plan_select_public on public.insurance_plan
  for select to anon, authenticated using (true);
create policy insurance_plan_insert on public.insurance_plan
  for insert to authenticated
  with check (
    (select private.is_admin())
    or ((select private.is_provider_or_admin()) and "providerId" = (select auth.uid()))
  );
create policy insurance_plan_update on public.insurance_plan
  for update to authenticated
  using ((select private.is_admin()) or ((select private.is_provider_or_admin()) and "providerId" = (select auth.uid())))
  with check ((select private.is_admin()) or ((select private.is_provider_or_admin()) and "providerId" = (select auth.uid())));
create policy insurance_plan_delete on public.insurance_plan
  for delete to authenticated
  using ((select private.is_admin()) or ((select private.is_provider_or_admin()) and "providerId" = (select auth.uid())));

revoke insert, update, delete, truncate, references, trigger
  on public.insurance_plan from anon;
revoke truncate, references, trigger
  on public.insurance_plan from authenticated;

-- ---------------------------------------------------------------------------
-- car_insurance_plan
-- ---------------------------------------------------------------------------

create table if not exists public.car_insurance_plan (
  "carId" bigint not null references public.car (id) on delete cascade,
  "insurancePlanId" bigint not null references public.insurance_plan (id) on delete cascade,
  "createdAt" timestamptz not null default now(),
  primary key ("carId", "insurancePlanId")
);

create index if not exists car_insurance_plan_plan_idx
  on public.car_insurance_plan ("insurancePlanId");

-- True when the current user may attach/detach this plan to/from this car:
-- admins always; providers only for their own car AND their own plan.
create or replace function private.can_link_insurance_plan(p_car_id bigint, p_plan_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    (select private.is_admin())
    or (
      (select private.is_provider_or_admin())
      and exists (
        select 1
        from public.car c
        join public.insurance_plan ip on ip."providerId" = c."providerId"
        where c.id = p_car_id
          and ip.id = p_plan_id
          and c."providerId" = (select auth.uid())
      )
    )
$$;

revoke all on function private.can_link_insurance_plan(bigint, bigint) from public;
grant execute on function private.can_link_insurance_plan(bigint, bigint) to authenticated;

alter table public.car_insurance_plan enable row level security;

drop policy if exists car_insurance_plan_select_public on public.car_insurance_plan;
drop policy if exists car_insurance_plan_insert on public.car_insurance_plan;
drop policy if exists car_insurance_plan_delete on public.car_insurance_plan;

create policy car_insurance_plan_select_public on public.car_insurance_plan
  for select to anon, authenticated using (true);
create policy car_insurance_plan_insert on public.car_insurance_plan
  for insert to authenticated
  with check ((select private.can_link_insurance_plan("carId", "insurancePlanId")));
create policy car_insurance_plan_delete on public.car_insurance_plan
  for delete to authenticated
  using ((select private.can_link_insurance_plan("carId", "insurancePlanId")));

-- Links are only added or removed, never edited
revoke insert, update, delete, truncate, references, trigger
  on public.car_insurance_plan from anon;
revoke update, truncate, references, trigger
  on public.car_insurance_plan from authenticated;

-- ---------------------------------------------------------------------------
-- booking: snapshot of the chosen plan
-- ---------------------------------------------------------------------------

alter table public.booking
  add column if not exists "insurancePlanId" bigint
    references public.insurance_plan (id) on delete set null,
  add column if not exists "insurancePlanName" text,
  add column if not exists "insurancePricePerDay" numeric(10,2),
  add column if not exists "insuranceTotal" numeric(10,2);

alter table public.booking
  drop constraint if exists booking_insurance_amounts_check;
alter table public.booking
  add constraint booking_insurance_amounts_check
    check (
      ("insurancePricePerDay" is null or "insurancePricePerDay" >= 0)
      and ("insuranceTotal" is null or "insuranceTotal" >= 0)
    );

create index if not exists booking_insurance_plan_idx
  on public.booking ("insurancePlanId");
